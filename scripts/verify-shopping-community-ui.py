"""Native browser flow against isolated local identities and storage only."""
import json, sys
from pathlib import Path
from urllib.parse import quote, urlparse, parse_qs
from playwright.sync_api import sync_playwright, expect

config=json.loads(Path(sys.argv[1]).read_text())
origin=config['origin']; output=Path(config['output'])
expect.set_options(timeout=90000)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
    context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,reduced_motion='reduce')
    context.add_cookies([{'name':'ames_customer_session','value':'qa-a','url':origin}])
    context.add_init_script("sessionStorage.setItem('ames_intro_seen','1')")
    context.route('**/*fontshare.com/**',lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    page=context.new_page(); page.set_default_timeout(90000)
    errors=[]; page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(origin+'/app?media='+quote(config['key']),wait_until='domcontentloaded',timeout=180000)
    card=page.locator('[data-media-item="'+config['key']+'"]')
    expect(card).to_be_visible()
    like=card.get_by_role('button',name='Like',exact=True)
    expect(like).to_be_enabled(); like.click(); expect(like).to_have_attribute('aria-pressed','true')
    save=card.get_by_role('button',name='Save video',exact=True)
    save.click(); expect(save).to_have_attribute('aria-pressed','true')
    card.get_by_role('button',name='Comment',exact=True).click()
    dialog=page.get_by_role('dialog')
    text='<script>window.__commentInjected=true</script>'
    dialog.get_by_role('textbox',name='Add a comment').fill(text)
    dialog.get_by_role('button',name='Post',exact=True).click()
    expect(dialog.get_by_text(text,exact=True)).to_be_visible()
    assert page.evaluate('window.__commentInjected') is None
    page.screenshot(path=str(output/'mobile-comments.png'))
    dialog.get_by_role('button',name='Close comments').click()
    card.get_by_role('button',name='Add to cart',exact=True).click()
    expect(card.get_by_text('In cart',exact=False)).to_be_visible()
    page.goto(origin+'/cart',wait_until='domcontentloaded')
    expect(page.get_by_text('Fixture video ring',exact=True)).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.get_by_role('checkbox').nth(0).check(); page.get_by_role('checkbox').nth(1).check()
    page.get_by_role('textbox').fill('Isolated browser fixture. No real delivery or payment.')
    page.screenshot(path=str(output/'mobile-cart.png'))
    page.get_by_role('button',name='Request bank-transfer invoice',exact=True).click()
    page.wait_for_url('**/app/billing?purchase=*')
    purchase=parse_qs(urlparse(page.url).query)['purchase'][0]
    expect(page.get_by_text('Status: requested',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='Confirm bank payment received')).to_have_count(0)
    page.goto(origin+'/workspace',wait_until='domcontentloaded')
    expect(page.locator('[data-saved-videos]').get_by_text('Fixture shoppable video',exact=True)).to_be_visible()
    page.screenshot(path=str(output/'mobile-saved-videos.png'))
    name,value=config['owner'].split('=',1)
    context.add_cookies([{'name':name,'value':value,'url':origin}])
    page.set_viewport_size({'width':820,'height':1180})
    page.goto(origin+'/dashboard/purchases?purchase='+purchase,wait_until='domcontentloaded')
    page.get_by_role('textbox',name='Invoice number',exact=True).fill('QA-BROWSER-INVOICE')
    page.get_by_role('textbox',name='Bank details, payment reference and agreed terms',exact=True).fill('QA ONLY. Do not send money. Isolated browser invoice with no real bank account.')
    page.get_by_role('textbox',name='Delivery amount',exact=True).fill('10')
    page.get_by_role('checkbox').check()
    page.get_by_role('button',name='Issue invoice',exact=True).click()
    expect(page.locator('[data-bank-invoice]')).to_be_visible()
    expect(page.get_by_text('Status: invoiced',exact=True)).to_be_visible()
    page.screenshot(path=str(output/'tablet-staff-invoice.png'))
    context.clear_cookies(); context.add_cookies([{'name':'ames_customer_session','value':'qa-a','url':origin}])
    page.goto(origin+'/app/billing?purchase='+purchase,wait_until='domcontentloaded')
    expect(page.locator('[data-bank-invoice]')).to_be_visible()
    expect(page.get_by_text('Status: invoiced',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='Confirm bank payment received')).to_have_count(0)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(output/'tablet-customer-invoice.png'))
    assert not errors, errors
    (output/'browser-report.json').write_text(json.dumps({'passed':True,'purchase':purchase,'pageErrors':errors,'physicalDevices':False},indent=2))
    browser.close()
print('PASS native mobile/tablet browser: like, save, escaped comment, cart, request, staff invoice, customer invoice')
